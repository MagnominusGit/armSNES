"""boards.py [boards.bml] [boards.inc]: turns ares's board database into a C table.

Each board becomes the list of its memory maps, each with what it connects to: the node path down
to it, such as "memory_ROM_Program" or "processor_W65C816S_mcu". The core connects the paths it knows
and declines boards with any it doesn't.
"""
import re
import sys

source = sys.argv[1] if len(sys.argv) > 1 else 'mia/Database/Super Famicom Boards.bml'
target = sys.argv[2] if len(sys.argv) > 2 else 'src/boards.inc'


def describe(name, attributes):
    if name == 'memory':
        return '_'.join(['memory', attributes.get('type', ''), attributes.get('content', '')] +
                        ([attributes['architecture']] if 'architecture' in attributes else []))
    if name == 'processor':
        return 'processor_' + (attributes.get('architecture') or attributes.get('identifier') or attributes.get('manufacturer'))
    if name == 'rtc':
        return 'rtc_' + attributes.get('manufacturer', '')
    if name == 'slot':
        return 'slot_' + attributes.get('type', '')
    return name


boards = []
stack = []
for line in open(source, encoding='utf-8'):
    line = line.rstrip('\n')
    if not line.strip() or line.lstrip().startswith('//'):
        continue
    depth = (len(line) - len(line.lstrip(' '))) // 2
    text = line.strip()
    if depth == 0:
        stack = []
        if text.startswith('board:'):
            boards.append({'name': text.split(':', 1)[1].strip(), 'maps': [], 'parts': []})
        else:
            boards.append(None)
        continue
    if not boards or boards[-1] is None:
        continue
    words = text.split()
    name = words[0]
    attributes = dict(w.split('=', 1) for w in words[1:] if '=' in w)
    del stack[depth - 1:]
    if name == 'map':
        path = '_'.join(stack) or 'board'
        boards[-1]['maps'].append((path, attributes.get('address'), attributes.get('size', '0'),
                                   attributes.get('base', '0'), attributes.get('mask', '0')))
    else:
        node = describe(name, attributes)
        stack.append(node)
        boards[-1]['parts'].append('_'.join(stack))

boards = [b for b in boards if b]
paths = sorted({m[0] for b in boards for m in b['maps']} | {p for b in boards for p in b['parts']})


def symbol(path):
    return 'PART_' + re.sub(r'[^A-Za-z0-9]', '_', path).upper()


out = ['// Generated by tools/boards.py from ares\'s board database (ISC); see LICENSES/ISC-ares.txt.', '',
       'enum BoardPart {', '\tPART_NONE,']
out += ['\t%s,' % symbol(p) for p in paths]
out += ['\tPART_COUNT,', '};', '']
out += ['static const char* const partNames[PART_COUNT] = {', '\t"",']
out += ['\t"%s",' % p for p in paths]
out += ['};', '']
out += ['struct BoardMap {', '\tu16 part;', '\tconst char* address;', '\tu32 size, base, mask;', '};', '',
        'struct BoardEntry {', '\tconst char* name;', '\tconst struct BoardMap* maps;', '\tu8 mapCount;',
        '\tconst u16* parts;', '\tu8 partCount;', '};', '']
for n, b in enumerate(boards):
    out.append('static const struct BoardMap board%dMaps[] = {' % n)
    for path, address, size, base, mask in b['maps']:
        out.append('\t{ %s, "%s", %s, %s, %s },' % (symbol(path), address, size, base, mask))
    if not b['maps']:
        out.append('\t{ 0 },')
    out.append('};')
    out.append('static const u16 board%dParts[] = { %s };' % (n, ', '.join(symbol(p) for p in b['parts']) or '0'))
out += ['', 'static const struct BoardEntry boardEntries[] = {']
for n, b in enumerate(boards):
    out.append('\t{ "%s", board%dMaps, %d, board%dParts, %d },' % (b['name'], n, len(b['maps']), n, len(b['parts'])))
out += ['};', '']
open(target, 'w').write('\n'.join(out))
print('%d boards, %d parts' % (len(boards), len(paths)))
